#!/usr/bin/env bash
# Run the KVM lane's acceptance receipt on one ephemeral GCP nested-KVM VM.
#
# Called from `.github/workflows/kernel-runtime.yml` (`kvm-tests`) on a hosted
# runner that is already authenticated to GCP through Workload Identity
# Federation. Design, trust boundary and debugging: docs/ci/gcp-kvm.md.
#
#   gcp-kvm-run.sh [run]            create VM, wait for its receipt, collect, delete
#   gcp-kvm-run.sh cleanup          delete this run's VM in any configured zone
#   gcp-kvm-run.sh startup-script   print the generated VM startup script
#
# Required environment:
#   GCP_PROJECT          project id (e.g. carrick-ci-261011)
#   GCP_RUNNER_VM_SA     VM service account email (objectCreator on the bucket)
#   GCP_RECEIPT_BUCKET   gs://bucket (results land in <bucket>/<run>/<attempt>/)
#   GITHUB_RUN_ID, GITHUB_RUN_ATTEMPT, GITHUB_SHA
# Optional:
#   GITHUB_SERVER_URL, GITHUB_REPOSITORY   clone source (default carrick-sh/carrick)
#   GCP_KVM_MACHINE_TYPE   default n2-standard-16
#   GCP_KVM_ZONES          comma list, default us-central1-a,us-central1-b,us-central1-c,us-central1-f
#   GCP_KVM_WAIT_MINUTES   bound on the wait for DONE/FAILED, default 150
#   GCP_KVM_POLL_SECONDS   poll interval, default 30
#   GCP_KVM_RECEIPT_OUT    default target/ci-receipts/receipt.json
#   GCP_KVM_LOGS_OUT       directory for downloaded logs, default target/ci-logs/gcp-kvm
#   GCP_KVM_RUSTUP_SHA256  rustup-init checksum (default: the Willow template's pin)
#   GCP_KVM_DRY_RUN=1      print the gcloud commands and startup script; run nothing
#
# Exit status: 0 when a receipt was collected (test failures are recorded in
# the receipt, never in this exit status); non-zero on a FAILED marker, a
# timeout, a missing receipt or a GCP error.
set -euo pipefail

die() {
    printf 'gcp-kvm: error: %s\n' "$*" >&2
    exit 1
}
log() { printf 'gcp-kvm: %s\n' "$*" >&2; }

mode=${1:-run}
case "$mode" in
    run | cleanup | startup-script) ;;
    -h | --help)
        sed -n '2,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'
        exit 0
        ;;
    *) die "unknown mode '$mode' (run | cleanup | startup-script)" ;;
esac

DRY_RUN=${GCP_KVM_DRY_RUN:-0}
PROJECT=${GCP_PROJECT:?GCP_PROJECT is required}
VM_SA=${GCP_RUNNER_VM_SA:?GCP_RUNNER_VM_SA is required}
BUCKET=${GCP_RECEIPT_BUCKET:?GCP_RECEIPT_BUCKET is required}
RUN_ID=${GITHUB_RUN_ID:?GITHUB_RUN_ID is required}
ATTEMPT=${GITHUB_RUN_ATTEMPT:-1}
SHA=${GITHUB_SHA:?GITHUB_SHA is required}
REPO_URL="${GITHUB_SERVER_URL:-https://github.com}/${GITHUB_REPOSITORY:-carrick-sh/carrick}"
MACHINE_TYPE=${GCP_KVM_MACHINE_TYPE:-n2-standard-16}
ZONES=${GCP_KVM_ZONES:-us-central1-a,us-central1-b,us-central1-c,us-central1-f}
WAIT_MINUTES=${GCP_KVM_WAIT_MINUTES:-150}
POLL_SECONDS=${GCP_KVM_POLL_SECONDS:-30}
RECEIPT_OUT=${GCP_KVM_RECEIPT_OUT:-target/ci-receipts/receipt.json}
LOGS_OUT=${GCP_KVM_LOGS_OUT:-target/ci-logs/gcp-kvm}
RUSTUP_SHA256=${GCP_KVM_RUSTUP_SHA256:-dda7234360b7f578ca8b0ddcb80145646fa61a67c1720a5abc7051b35c9fcb71}

# Everything below is interpolated into gcloud arguments, label values and the
# startup script; reject anything outside the expected shapes up front.
[[ "$SHA" =~ ^[0-9a-f]{40}$ ]] || die "GITHUB_SHA must be a full lowercase commit SHA: '$SHA'"
[[ "$RUN_ID" =~ ^[0-9]+$ ]] || die "GITHUB_RUN_ID must be numeric: '$RUN_ID'"
[[ "$ATTEMPT" =~ ^[0-9]+$ ]] || die "GITHUB_RUN_ATTEMPT must be numeric: '$ATTEMPT'"
[[ "$PROJECT" =~ ^[a-z][a-z0-9-]{4,28}[a-z0-9]$ ]] || die "bad GCP_PROJECT '$PROJECT'"
[[ "$VM_SA" =~ ^[a-z0-9-]+@[a-z0-9.-]+$ ]] || die "bad GCP_RUNNER_VM_SA '$VM_SA'"
[[ "$MACHINE_TYPE" =~ ^[a-z0-9-]+$ ]] || die "bad GCP_KVM_MACHINE_TYPE '$MACHINE_TYPE'"
[[ "$ZONES" =~ ^[a-z0-9-]+(,[a-z0-9-]+)*$ ]] || die "bad GCP_KVM_ZONES '$ZONES'"
[[ "$WAIT_MINUTES" =~ ^[0-9]+$ && "$POLL_SECONDS" =~ ^[0-9]+$ ]] || die "wait/poll must be integers"
[[ "$RUSTUP_SHA256" =~ ^[0-9a-f]{64}$ ]] || die "bad GCP_KVM_RUSTUP_SHA256"
[[ "$REPO_URL" =~ ^https://[A-Za-z0-9./_-]+$ ]] || die "bad clone URL '$REPO_URL'"
BUCKET=${BUCKET%/}
[[ "$BUCKET" == gs://* ]] || BUCKET="gs://$BUCKET"
[[ "$BUCKET" =~ ^gs://[a-z0-9][a-z0-9._-]{1,220}$ ]] || die "bad GCP_RECEIPT_BUCKET '$BUCKET'"
PREFIX="$BUCKET/$RUN_ID/$ATTEMPT"

# kvm-<run_id>-<attempt>-<short sha>: RFC 1035, lowercase, <= 63 characters.
NAME="kvm-${RUN_ID}-${ATTEMPT}-${SHA:0:8}"
NAME=${NAME:0:63}
NAME=${NAME%-}
IFS=',' read -r -a ZONE_LIST <<<"$ZONES"

# Print (dry run) or execute one gcloud command.
gc() {
    if [ "$DRY_RUN" = 1 ]; then
        printf '+ gcloud'
        printf ' %q' "$@"
        printf '\n'
        return 0
    fi
    gcloud "$@"
}

startup_script() {
    # Values first (shell-quoted), then a static body: nothing in the body is
    # expanded by this generator.
    printf '#!/bin/bash\n'
    printf '# Generated by scripts/ci/gcp-kvm-run.sh for %s run %s attempt %s.\n' "$REPO_URL" "$RUN_ID" "$ATTEMPT"
    printf 'readonly CARRICK_SHA=%q\n' "$SHA"
    printf 'readonly CARRICK_REPO_URL=%q\n' "$REPO_URL"
    printf 'readonly CARRICK_PREFIX=%q\n' "$PREFIX"
    printf 'readonly CARRICK_RUSTUP_SHA256=%q\n' "$RUSTUP_SHA256"
    cat <<'BODY'
set -euo pipefail
readonly LOG=/var/log/carrick-kvm.log
readonly STATE=/var/lib/carrick-kvm
readonly USER_NAME=carrick
readonly REPO=/home/carrick/carrick
mkdir -p "$STATE"
# Everything goes to the serial console (the controller tails it) and a log file
# (uploaded on success and failure). Nothing reaches the script runner, so the
# serial console carries each line once.
if [ -w /dev/ttyS0 ]; then
    exec > >(tee -a "$LOG" > /dev/ttyS0) 2>&1
else
    exec > >(tee -a "$LOG") 2>&1
fi
say() { printf '[carrick-kvm %s] %s\n' "$(date -u +%H:%M:%S)" "$*"; }

# Upload one file to the run prefix with the VM service account (metadata
# credentials). The account is objectCreator only: new objects, no overwrite,
# no read. gcloud is preferred; the JSON API via curl covers an image without it.
upload() {
    local src=$1 name=$2
    if command -v gcloud >/dev/null 2>&1 &&
        gcloud storage cp --quiet "$src" "$CARRICK_PREFIX/$name"; then
        return 0
    fi
    local token bucket object
    token=$(curl -fsS -H 'Metadata-Flavor: Google' \
        http://metadata.google.internal/computeMetadata/v1/instance/service-accounts/default/token |
        sed -n 's/.*"access_token" *: *"\([^"]*\)".*/\1/p')
    bucket=${CARRICK_PREFIX#gs://}
    bucket=${bucket%%/*}
    object="${CARRICK_PREFIX#gs://"$bucket"/}/$name"
    curl -fsS -o /dev/null -X POST -H "Authorization: Bearer $token" \
        -H 'Content-Type: application/octet-stream' --data-binary @"$src" \
        "https://storage.googleapis.com/upload/storage/v1/b/$bucket/o?uploadType=media&name=${object//\//%2F}"
}

finish() {
    local rc=$?
    trap - EXIT
    if [ ! -e "$STATE/done" ]; then
        say "setup failed (exit $rc); uploading FAILED marker"
        {
            printf 'carrick-kvm setup failed with exit %s at %s\n' "$rc" "$(date -u +%FT%TZ)"
            printf -- '--- last 200 log lines ---\n'
            tail -n 200 "$LOG" 2>/dev/null || true
        } > "$STATE/FAILED"
        upload "$LOG" startup.log || true
        upload "$STATE/FAILED" FAILED || say "could not upload the FAILED marker"
    fi
    exit "$rc"
}

if [ -e "$STATE/started" ]; then
    # A reboot reruns startup scripts. One VM = one attempt: never rerun the lane.
    say "startup script already ran on this VM; refusing to rerun"
    trap finish EXIT
    exit 1
fi
touch "$STATE/started"
trap finish EXIT
say "lane start: $CARRICK_REPO_URL @ $CARRICK_SHA -> $CARRICK_PREFIX"

# Mirrors the Willow template's package set (scripts/ci/build-template-debian.sh)
# plus pkg-config/libssl-dev for openssl-sys and nftables for the guard below.
say "installing build dependencies"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q --no-install-recommends \
    build-essential clang git curl ca-certificates jq just util-linux procps \
    pkg-config libssl-dev nftables

# Test code runs as $USER_NAME. It reaches crates.io/GitHub (and the metadata
# DNS resolver) but not the metadata HTTP endpoint, so it cannot mint the VM
# account's token and write to the receipt bucket itself; only this root
# script uploads.
getent group kvm >/dev/null || groupadd --system kvm
id "$USER_NAME" >/dev/null 2>&1 || useradd -m -s /bin/bash -G kvm "$USER_NAME"
nft -f - <<'NFT'
table inet carrick_kvm_guard {
  chain output {
    type filter hook output priority 0; policy accept;
    meta skuid "carrick" ip daddr 169.254.169.254 tcp dport 80 reject
    meta skuid "carrick" ip6 daddr fd20:ce::254 tcp dport 80 reject
  }
}
NFT

say "verifying /dev/kvm"
test -c /dev/kvm
grep -Eq 'vmx|svm' /proc/cpuinfo
chgrp kvm /dev/kvm
chmod 0660 /dev/kvm
runuser -u "$USER_NAME" -- test -r /dev/kvm
runuser -u "$USER_NAME" -- test -w /dev/kvm
ls -l /dev/kvm
nproc
free -g

say "fetching exact commit"
runuser -l "$USER_NAME" -c "set -euo pipefail
git init -q '$REPO'
git -C '$REPO' remote add origin '$CARRICK_REPO_URL'
git -C '$REPO' fetch -q --depth=1 origin '$CARRICK_SHA'
git -C '$REPO' checkout -q --detach FETCH_HEAD
test \"\$(git -C '$REPO' rev-parse HEAD)\" = '$CARRICK_SHA'"

say "installing rustup and the pinned toolchain"
curl -fsSL --retry 3 https://static.rust-lang.org/rustup/dist/x86_64-unknown-linux-gnu/rustup-init \
    -o /tmp/rustup-init
printf '%s  %s\n' "$CARRICK_RUSTUP_SHA256" /tmp/rustup-init | sha256sum -c -
chmod 0755 /tmp/rustup-init
channel=$(sed -n 's/^channel = "\([^"]*\)"/\1/p' "$REPO/rust-toolchain.toml")
test -n "$channel"
runuser -l "$USER_NAME" -c "/tmp/rustup-init -y -q --no-modify-path --profile minimal --default-toolchain '$channel'"
runuser -l "$USER_NAME" -c "set -euo pipefail
. \"\$HOME/.cargo/env\"
cd '$REPO'
# rust-toolchain.toml's components and targets (rustup >= 1.28 needs an explicit install).
rustup toolchain install || rustup show
rustup target add x86_64-unknown-none x86_64-unknown-linux-musl
rustc --version
cargo --version
just --version"

say "running: just accept --profile kvm"
set +e
runuser -l "$USER_NAME" -c "set -euo pipefail
. \"\$HOME/.cargo/env\"
cd '$REPO'
rm -rf target/ci-receipts
mkdir -p target/ci-receipts
just accept --profile kvm --receipt target/ci-receipts/receipt.json"
status=$?
set -e
say "xtask accept exited $status"

# Results. A FAIL receipt is still a receipt; the hosted gate compares it.
receipt="$REPO/target/ci-receipts/receipt.json"
receipt_present=false
if [ -s "$receipt" ]; then
    receipt_present=true
    upload "$receipt" receipt.json
fi
if [ -d "$REPO/target/el1-gate" ]; then
    tar -C "$REPO/target" -czf "$STATE/accept-logs.tar.gz" el1-gate
    upload "$STATE/accept-logs.tar.gz" accept-logs.tar.gz
fi
jq -n --arg sha "$CARRICK_SHA" --argjson status "$status" \
    --argjson receipt "$receipt_present" --arg finished "$(date -u +%FT%TZ)" \
    '{sha: $sha, accept_exit_status: $status, receipt: $receipt, finished: $finished}' \
    > "$STATE/status.json"
upload "$STATE/status.json" status.json
cp "$LOG" "$STATE/startup.log"
upload "$STATE/startup.log" startup.log
# DONE last: the controller treats it as "every other object is in place".
cp "$STATE/status.json" "$STATE/DONE"
upload "$STATE/DONE" DONE
touch "$STATE/done"
say "lane done; the controller deletes this VM (backstop: max-run-duration)"
BODY
}

instance_zone() {
    # The zone holding this run's instance, or nothing.
    gcloud compute instances list --project "$PROJECT" \
        --filter="name=($NAME)" --format='value(zone.basename())' 2>/dev/null | head -n1
}

delete_instance() {
    local zone=$1
    [ -n "$zone" ] || return 0
    log "deleting $NAME in $zone"
    if [ "$DRY_RUN" = 1 ]; then
        gc compute instances delete "$NAME" --project "$PROJECT" --zone "$zone" --quiet
        return 0
    fi
    local out
    if ! out=$(gcloud compute instances delete "$NAME" --project "$PROJECT" --zone "$zone" --quiet 2>&1); then
        if grep -qiE 'not found|notFound|was not found' <<<"$out"; then
            return 0
        fi
        printf '%s\n' "$out" >&2
        log "WARNING: delete failed; max-run-duration=3h deletes it as a backstop"
        return 0
    fi
}

if [ "$mode" = startup-script ]; then
    startup_script
    exit 0
fi

if [ "$mode" = cleanup ]; then
    if [ "$DRY_RUN" = 1 ]; then
        gc compute instances list --project "$PROJECT" --filter="name=($NAME)" --format='value(zone.basename())'
        exit 0
    fi
    delete_instance "$(instance_zone)"
    exit 0
fi

# ---- run ----------------------------------------------------------------
workdir=$(mktemp -d)
ZONE=""
cleanup() {
    local rc=$?
    trap - EXIT INT TERM
    delete_instance "$ZONE"
    rm -rf "$workdir"
    exit "$rc"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

startup_script > "$workdir/startup.sh"
if [ "$DRY_RUN" = 1 ]; then
    log "dry run: instance $NAME, machine $MACHINE_TYPE, zones ${ZONE_LIST[*]}, prefix $PREFIX"
    printf -- '----- generated startup script -----\n'
    cat "$workdir/startup.sh"
    printf -- '----- end startup script -----\n'
fi

create_args=(
    compute instances create "$NAME"
    --project "$PROJECT"
    --machine-type "$MACHINE_TYPE"
    --enable-nested-virtualization
    --image-family debian-13
    --image-project debian-cloud
    --boot-disk-size 100GB
    --boot-disk-type pd-ssd
    --service-account "$VM_SA"
    --scopes cloud-platform
    --max-run-duration 3h
    --instance-termination-action DELETE
    --labels "carrick-lane=kvm,run-id=$RUN_ID,run-attempt=$ATTEMPT,sha=$SHA"
    --metadata block-project-ssh-keys=TRUE
    --metadata-from-file "startup-script=$workdir/startup.sh"
)

# Capacity is zonal: try the next zone. Anything else (quota, permissions,
# bad flags) is not going to improve elsewhere.
capacity_re='ZONE_RESOURCE_POOL_EXHAUSTED|STOCKOUT|does not have enough resources|resource_availability|currently unavailable in the .* zone'
for zone in "${ZONE_LIST[@]}"; do
    ZONE=$zone
    log "creating $NAME ($MACHINE_TYPE) in $zone"
    if [ "$DRY_RUN" = 1 ]; then
        gc "${create_args[@]}" --zone "$zone"
        break
    fi
    if out=$(gcloud "${create_args[@]}" --zone "$zone" 2>&1); then
        printf '%s\n' "$out" >&2
        break
    fi
    printf '%s\n' "$out" >&2
    if grep -qE "$capacity_re" <<<"$out"; then
        # The request may still have left an instance record; clear it.
        delete_instance "$zone"
        ZONE=""
        log "no capacity in $zone; trying the next zone"
        continue
    fi
    die "instance creation failed in $zone (not a capacity error)"
done
[ -n "$ZONE" ] || die "no capacity for $MACHINE_TYPE in any of: ${ZONE_LIST[*]}"

# ---- wait -----------------------------------------------------------------
serial_next=0
stream_serial() {
    local json
    json=$(gcloud compute instances get-serial-port-output "$NAME" --project "$PROJECT" \
        --zone "$ZONE" --start="$serial_next" --format=json 2>/dev/null) || return 0
    local contents next
    contents=$(jq -r '.contents // ""' <<<"$json" 2>/dev/null) || return 0
    next=$(jq -r '.next // empty' <<<"$json" 2>/dev/null) || next=""
    [ -n "$contents" ] && printf '%s' "$contents" | sed 's/^/  | /'
    [[ "$next" =~ ^[0-9]+$ ]] && serial_next=$next
    return 0
}

if [ "$DRY_RUN" = 1 ]; then
    gc storage ls "$PREFIX/"
    gc compute instances get-serial-port-output "$NAME" --project "$PROJECT" --zone "$ZONE" --start=0 --format=json
    gc storage cp "$PREFIX/receipt.json" "$RECEIPT_OUT"
    gc storage cp "$PREFIX/status.json" "$PREFIX/startup.log" "$PREFIX/accept-logs.tar.gz" "$LOGS_OUT/"
    log "dry run complete; cleanup would run: gcloud compute instances delete $NAME --zone $ZONE --quiet"
    ZONE=""
    exit 0
fi

deadline=$(($(date +%s) + WAIT_MINUTES * 60))
outcome=timeout
log "waiting up to ${WAIT_MINUTES} min for $PREFIX/{DONE,FAILED}"
while [ "$(date +%s)" -lt "$deadline" ]; do
    stream_serial
    listing=$(gcloud storage ls "$PREFIX/" 2>/dev/null || true)
    if grep -qx "$PREFIX/DONE" <<<"$listing"; then
        outcome=finished
        break
    fi
    if grep -qx "$PREFIX/FAILED" <<<"$listing"; then
        outcome=failed
        break
    fi
    status=$(gcloud compute instances describe "$NAME" --project "$PROJECT" --zone "$ZONE" \
        --format='value(status)' 2>/dev/null || echo GONE)
    case "$status" in
        GONE | TERMINATED | STOPPING | STOPPED | SUSPENDED)
            # One last look: the marker may have landed just before.
            sleep 5
            listing=$(gcloud storage ls "$PREFIX/" 2>/dev/null || true)
            grep -qx "$PREFIX/DONE" <<<"$listing" && { outcome=finished; break; }
            grep -qx "$PREFIX/FAILED" <<<"$listing" && { outcome=failed; break; }
            die "instance $NAME is $status before writing DONE/FAILED (preempted, backstop-deleted or crashed?)"
            ;;
    esac
    sleep "$POLL_SECONDS"
done
stream_serial

# ---- collect --------------------------------------------------------------
mkdir -p "$(dirname "$RECEIPT_OUT")" "$LOGS_OUT"
rm -f "$RECEIPT_OUT"
for obj in status.json startup.log accept-logs.tar.gz FAILED; do
    gcloud storage cp --quiet "$PREFIX/$obj" "$LOGS_OUT/$obj" >/dev/null 2>&1 || true
done
case "$outcome" in
    timeout)
        die "no DONE/FAILED marker under $PREFIX after ${WAIT_MINUTES} min"
        ;;
    failed)
        printf -- '----- FAILED marker from the VM -----\n' >&2
        cat "$LOGS_OUT/FAILED" >&2 || true
        die "VM setup failed before producing a receipt (see above, $PREFIX/startup.log)"
        ;;
esac
[ -s "$LOGS_OUT/status.json" ] && log "status: $(cat "$LOGS_OUT/status.json")"
gcloud storage cp --quiet "$PREFIX/receipt.json" "$RECEIPT_OUT" ||
    die "DONE without a receipt under $PREFIX (accept crashed before writing one; see $LOGS_OUT)"
test -s "$RECEIPT_OUT" || die "empty receipt at $RECEIPT_OUT"
log "receipt collected: $RECEIPT_OUT"
