//! PR-time check for gated tests dropped or renamed without a declaration.
//!
//! The receipt gate (`ci_receipt`) reads a test that vanished from the
//! candidate as `missing:` unless `.github/retired-tests.toml` declares it.
//! That fires after landing, on main. This check runs the same source scanner
//! and lane metadata over the merge base and the head instead, so the PR that
//! drops the test fails its own CI and is told which entry to add.
//!
//! Presence is by `(test binary, module path::fn name)`, the identity a
//! receipt records and `[[retired]]` declares. The binary is the cargo target
//! whose `mod` tree holds the test, not a directory name. A test moved to
//! another module of its binary therefore reads as dropped, as the receipt
//! gate reads it.

use crate::ci_receipt::{
    CrateTestInventory, RETIRED_TESTS_PATH, ReceiptError, load_retired_tests, tree_test_inventory,
};
use std::collections::BTreeSet;
use std::path::Path;
use std::process::{Command, Stdio};

#[derive(Debug, clap::Args)]
pub struct RetiredTestsArgs {
    /// Revision to compare against; the merge base with `--head` is used, so
    /// tests main removed after the PR branched are not charged to the PR.
    /// Absent or empty skips the check, like `authority-debt --base`.
    #[arg(long, env = "CARRICK_AUTHORITY_BASE")]
    pub base: Option<String>,
    /// Head revision whose tree is checked.
    #[arg(long, default_value = "HEAD")]
    pub head: String,
}

/// A gated test present in the base and absent from the head, undeclared.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UndeclaredRetirement {
    pub bin: String,
    pub test: String,
    pub lane: String,
}

impl UndeclaredRetirement {
    fn entry(&self) -> String {
        format!(
            "[[retired]]\ntest = \"{}::{}\"\nreason = \"<why it was renamed or removed>\"\npr = <this PR number>\n# replaced_by = \"{}::<new name>\"   # when renamed",
            self.bin, self.test, self.bin
        )
    }
}

/// Pure comparison of two inventories against the head's declarations.
pub fn undeclared(
    base: &[CrateTestInventory],
    head: &[CrateTestInventory],
    declared: &BTreeSet<(String, String)>,
    warnings: &mut Vec<String>,
) -> Vec<UndeclaredRetirement> {
    let in_head: BTreeSet<&(String, String)> = head.iter().flat_map(|c| c.tests.keys()).collect();
    let mut out = Vec::new();
    let mut generators: Vec<&str> = Vec::new();
    for krate in base {
        if krate.unresolved.is_some() {
            generators.push(krate.crate_name.as_str());
        }
        for (key, lane) in &krate.tests {
            if lane == "manual" || in_head.contains(key) || declared.contains(key) {
                continue;
            }
            out.push(UndeclaredRetirement {
                bin: key.0.clone(),
                test: key.1.clone(),
                lane: lane.clone(),
            });
        }
    }
    if !generators.is_empty() {
        warnings.push(format!(
            "tests generated by macros or #[path] modules are not inventoried in {} crate(s): {}",
            generators.len(),
            generators.join(", ")
        ));
    }
    out.sort_by(|a, b| (&a.bin, &a.test).cmp(&(&b.bin, &b.test)));
    out.dedup();
    out
}

fn git(root: &Path, args: &[&str]) -> Result<Vec<u8>, ReceiptError> {
    let out = Command::new("git")
        .args(args)
        .current_dir(root)
        .output()
        .map_err(|e| ReceiptError::Retired(format!("git unavailable: {e}")))?;
    if !out.status.success() {
        return Err(ReceiptError::Retired(format!(
            "git {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr).trim()
        )));
    }
    Ok(out.stdout)
}

/// Extract the test-bearing paths of `rev` into `dest` (no worktree, no
/// checkout state touched).
fn extract(root: &Path, rev: &str, dest: &Path) -> Result<(), ReceiptError> {
    // Only paths that exist at `rev`: `git archive` rejects a missing pathspec.
    let wanted = [
        "crates",
        "conformance-probes",
        "tests",
        "src",
        RETIRED_TESTS_PATH,
    ];
    let mut paths = Vec::new();
    for path in wanted {
        if !git(root, &["ls-tree", "--name-only", rev, "--", path])?.is_empty() {
            paths.push(path);
        }
    }
    let mut archive = Command::new("git");
    archive
        .args(["archive", rev, "--"])
        .args(&paths)
        .current_dir(root)
        .stdout(Stdio::piped());
    let mut child = archive
        .spawn()
        .map_err(|e| ReceiptError::Retired(format!("git archive: {e}")))?;
    let tar = Command::new("tar")
        .args(["-x", "-C"])
        .arg(dest)
        .stdin(
            child
                .stdout
                .take()
                .ok_or_else(|| ReceiptError::Retired("git archive: no stdout".into()))?,
        )
        .status()
        .map_err(|e| ReceiptError::Retired(format!("tar: {e}")))?;
    let archived = child
        .wait()
        .map_err(|e| ReceiptError::Retired(format!("git archive: {e}")))?;
    if !tar.success() || !archived.success() {
        return Err(ReceiptError::Retired(format!("cannot extract {rev}")));
    }
    Ok(())
}

pub fn run(root: &Path, args: &RetiredTestsArgs) -> Result<(), ReceiptError> {
    let resolve = |rev: &str| -> Result<String, ReceiptError> {
        let out = git(
            root,
            &["rev-parse", "--verify", &format!("{rev}^{{commit}}")],
        )?;
        Ok(String::from_utf8_lossy(&out).trim().to_string())
    };
    let Some(requested) = args
        .base
        .as_deref()
        .map(str::trim)
        .filter(|b| !b.is_empty())
    else {
        println!("retired-tests: no base provided; check not applicable");
        return Ok(());
    };
    let head = resolve(&args.head)?;
    let base = resolve(requested)?;
    let base = String::from_utf8_lossy(&git(root, &["merge-base", &base, &head])?)
        .trim()
        .to_string();
    if base == head {
        println!("retired-tests: head is the base; nothing to compare");
        return Ok(());
    }
    let io = |e: std::io::Error| ReceiptError::Retired(format!("tempdir: {e}"));
    let base_dir = tempfile::tempdir().map_err(io)?;
    let head_dir = tempfile::tempdir().map_err(io)?;
    extract(root, &base, base_dir.path())?;
    extract(root, &head, head_dir.path())?;
    let declared: BTreeSet<(String, String)> = load_retired_tests(head_dir.path())?
        .iter()
        .filter_map(|entry| {
            let (bin, path) = entry.test.split_once("::")?;
            Some((bin.to_string(), path.to_string()))
        })
        .collect();
    let mut warnings = Vec::new();
    let missing = undeclared(
        &tree_test_inventory(base_dir.path())?,
        &tree_test_inventory(head_dir.path())?,
        &declared,
        &mut warnings,
    );
    for warning in &warnings {
        println!("WARNING: {warning}");
    }
    if missing.is_empty() {
        println!("retired-tests: no gated test dropped or renamed without a declaration");
        return Ok(());
    }
    let mut message = format!(
        "{} gated test(s) exist at base {} but not at head {} and have no [[retired]] entry in {RETIRED_TESTS_PATH}; main's receipt gate would read them as `missing:`.\nAdd, per test:\n",
        missing.len(),
        &base[..12],
        &head[..12]
    );
    for m in &missing {
        message.push_str(&format!(
            "\n  {}::{} (lane {})\n{}\n",
            m.bin,
            m.test,
            m.lane,
            m.entry()
                .lines()
                .map(|l| format!("    {l}"))
                .collect::<Vec<_>>()
                .join("\n")
        ));
    }
    message.push_str("\nSee docs/ci/mac-hvf-runner.md, \"Retiring or renaming gated tests\".");
    Err(ReceiptError::Retired(message))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn krate(tests: &[(&str, &str, &str)]) -> CrateTestInventory {
        CrateTestInventory {
            crate_name: "demo".into(),
            tests: tests
                .iter()
                .map(|(b, t, l)| ((b.to_string(), t.to_string()), l.to_string()))
                .collect(),
            unresolved: None,
        }
    }

    #[test]
    fn a_renamed_gated_test_is_reported_until_declared() {
        let base = [krate(&[
            ("kvm_bin", "old", "kvm"),
            ("kvm_bin", "kept", "kvm"),
        ])];
        let head = [krate(&[
            ("kvm_bin", "new", "kvm"),
            ("kvm_bin", "kept", "kvm"),
        ])];
        let mut warnings = Vec::new();
        let missing = undeclared(&base, &head, &BTreeSet::new(), &mut warnings);
        assert_eq!(
            missing,
            [UndeclaredRetirement {
                bin: "kvm_bin".into(),
                test: "old".into(),
                lane: "kvm".into()
            }]
        );
        assert!(missing[0].entry().contains("test = \"kvm_bin::old\""));
        let declared = BTreeSet::from([("kvm_bin".to_string(), "old".to_string())]);
        assert!(undeclared(&base, &head, &declared, &mut warnings).is_empty());
    }

    #[test]
    fn manual_lane_tests_are_not_gated() {
        let base = [krate(&[("hw", "needs_hardware", "manual")])];
        let mut warnings = Vec::new();
        assert!(undeclared(&base, &[krate(&[])], &BTreeSet::new(), &mut warnings).is_empty());
    }

    #[test]
    fn a_test_moved_to_another_binary_needs_a_declaration() {
        let base = [krate(&[("a", "t", "host")])];
        let head = [krate(&[("b", "t", "host")])];
        let mut warnings = Vec::new();
        assert_eq!(
            undeclared(&base, &head, &BTreeSet::new(), &mut warnings).len(),
            1
        );
    }
}
